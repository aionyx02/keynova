#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import { ROOT, parseFrontmatter, repoPath, todayTaipei, walkMarkdown } from "./docs-utils.mjs";

const SESSION_ROOTS = [
  path.join(ROOT, "docs", "memory", "sessions"),
  path.join(ROOT, "docs", "memory", "archive"),
];

const completedItems = [];

for (const root of SESSION_ROOTS) {
  for (const filePath of walkMarkdown(root)) {
    const file = repoPath(filePath);
    const dateMatch = path.basename(filePath).match(/^(\d{4}-\d{2}-\d{2})/);
    if (!dateMatch) {
      continue;
    }
    const { body } = parseFrontmatter(fs.readFileSync(filePath, "utf8"));
    for (const match of body.matchAll(/^## COMPLETED:\s*(.+?)\s+-\s+(.+)$/gm)) {
      completedItems.push({
        date: dateMatch[1],
        taskId: match[1].trim(),
        summary: match[2].trim(),
        file,
      });
    }
  }
}

completedItems.sort((a, b) => b.date.localeCompare(a.date) || a.taskId.localeCompare(b.taskId));

const today = todayTaipei();
let output = `---
type: task_archive_index
status: archive
priority: p3
updated: ${today}
context_policy: on_demand
owner: project
auto_generated: true
---

# Completed Tasks (Index)

<!-- AUTO-GENERATED by scripts/docs-completed-regen.mjs. Do not hand-edit details here. -->

`;

if (completedItems.length === 0) {
  output += "No completed task markers found in session logs.\n";
} else {
  let currentMonth = "";
  for (const item of completedItems) {
    const month = item.date.slice(0, 7);
    if (month !== currentMonth) {
      currentMonth = month;
      output += `## ${month}\n\n`;
    }
    output += `- **${item.taskId}** ${item.summary} (${item.date}) - Detail: \`${item.file}\`\n`;
  }
}

const targetPath = path.join(ROOT, "docs", "tasks", "completed.md");
fs.writeFileSync(targetPath, output.trimEnd() + "\n", "utf8");
console.log(
  `[docs-completed-regen] Wrote ${repoPath(targetPath)} with ${completedItems.length} items.`,
);
